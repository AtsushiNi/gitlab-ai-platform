"""実装計画用のプロンプト(instructions)を組み立てる。

`design/prompts.py`の`build_design_instructions`と対になるモジュール
(M4-7 [#113](https://github.com/AtsushiNi/gitlab-ai-platform/issues/113))。ここで返す文字列は
`runner.build_issue_prompt`の`instructions`引数にそのまま渡す。`build_issue_prompt`が
この文字列の直後にIssueタイトル・説明・ラベルを自動的に追記する(`docs/specs/claude-code-runner.md`)。

`build_design_instructions`と同じく`PlanInput`(設計フェーズが確定させた設計内容・前提)を
引数に取る決定的な処理で、Issue固有のデータ(タイトル・説明・ラベル)は含めない。

ADR-0030の決定により、実装計画フェーズもWorkspace Manager(worktree)を使わずリポジトリを
探索しない(`design`と同じくADR-0027の設計を踏襲)。そのため、実在するかどうか確認できない
ファイルパス・関数名を断定的に書かないよう明示的に指示する。

出力スキーマは`types.PlanResult`・`orchestrator.types.Uncertainty`と1対1になるよう設計しており、
`parser.py`がここでの指示を前提に`result_text`をパースする(指示とパーサーの実装が食い違うと
壊れるため、変更時は両方を見る)。
"""

from __future__ import annotations

from .types import PlanInput


def build_plan_instructions(plan_input: PlanInput) -> str:
    """実装計画用のinstructions文字列を返す。

    `plan_input`(設計フェーズが確定させた設計内容・前提)をテキストに埋め込む決定的な処理
    (同じ`plan_input`を渡せば常に同じ文字列を返す)。Issueごとの情報(タイトル・説明・ラベル)は
    含めない。それらは`runner.build_issue_prompt`が`instructions`の直後に自動で追記する。
    """
    assumed_uncertainties = _bullet_list(
        plan_input.assumed_uncertainties, empty="(前提はありません)"
    )

    return f"""あなたは経験豊富なテックリードです。これから提示する設計内容を元に、実装に着手できる
粒度までタスクを分解してください。

**これは無人実行トラック専用のフェーズです。** 人間と対話しながら実装を進める対話型トラック
(VS Code拡張)では、対話の中で自然にタスクの分解が行われるため、このフェーズ自体が不要です。
このフェーズはIssueに無人実行ラベルが付いた場合にのみ実行されます。

## 入力: 設計フェーズの結果

以下は前段の設計フェーズで既に確定した内容です。**蒸し返さず、そのまま前提としてタスク分解に
使ってください。**

### 設計文書

{plan_input.design_document}

### 前提

{assumed_uncertainties}

## 制約: リポジトリを参照できません

このフェーズはIssue本文と上記の設計文書のみを入力とし、対象プロジェクトの実際のソースコードを
参照できません。そのため、次の点に注意してください。

- 実在するかどうか確認できないファイルパス・関数名・クラス名を断定的に書かない
- 「〇〇というファイルの△△行目を変更する」のような実装詳細ではなく、「〇〇という責務を持つ
  コンポーネントに△△の処理を追加する」のような粒度でタスクを書く
- 既存コードとの整合性が必要な判断(命名規則・アーキテクチャパターン等)は、実装フェーズが
  実際のコードを見て解決する前提を明示する

## 進め方

設計文書を、次の基準を満たす実装可能な粒度のタスクへ分解してください。

- 1タスクは1回のcommitで完結する程度の大きさにする(大きすぎず、細かすぎない)
- タスクは実装順に並べる(後続のタスクが前提とする変更は、先行するタスクで完了している状態を保つ)
- 各タスクは「何を実装するか」「完了の目安」が分かる説明を持つ

そのうえで、次の構成でMarkdown形式の実装計画文書を作成してください:

1. **概要**: このIssueの実装をどのような順序・方針で進めるか(1〜3文)
2. **タスク一覧**: 実装順に並べたタスクの箇条書き(各タスクの見出しと内容)
3. **前提と非対象**: タスク分解にあたって置いた前提、意図的に対象外にしたこと

## 不足情報の重要度

タスク分解を進める上で設計文書だけでは判断できない不明点が生じた場合、1件ごとに次のいずれかの
重要度を付けてください。

- `critical`: タスク分解の方向性そのものを左右する重要な不明点。人間に確認せずに進めると
  誤ったタスク分解になりうるもの
- `minor`: 軽微な疑問。妥当な仮定を1つ置いて進めても大きな問題にならないもの。
  この場合は採用する仮定の内容も一緒に示すこと

## 出力

応答の最後に、実装計画の結果を機械可読な形式でまとめた ```json のコードブロックを
**必ず1つだけ**出力してください。このコードブロック以降に他のテキストを続けないでください。
JSONは次のスキーマに従うオブジェクトにしてください。

- `plan_document`: 文字列。上記の構成に従って作成した実装計画文書全文(Markdown)
- `tasks`: 配列。実装順に並べたタスクの一覧。1件以上必須。各要素は以下のフィールドを持つオブジェクト:
  - `title`: タスクの短い見出し
  - `description`: タスクの内容(何を実装するか、完了の目安)
- `open_questions`: 配列。不足情報(不明点)の一覧。無理に作らず、無ければ空配列 `[]`。
  各要素は以下のフィールドを持つオブジェクト:
  - `question`: 不明点の内容
  - `severity`: 重要度。`"critical"` または `"minor"`
  - `assumption`: `severity`が`"minor"`の場合、採用する仮定の内容(必須)。
    `"critical"`の場合は省略するか`null`にする

出力は日本語で書いてください(JSON内の文字列値も日本語で構いません)。

(この指示の後に、対象のIssueタイトル・説明・ラベルが続きます)"""


def _bullet_list(items: tuple[str, ...], *, empty: str) -> str:
    if not items:
        return empty
    return "\n".join(f"- {item}" for item in items)


__all__ = ["build_plan_instructions"]
