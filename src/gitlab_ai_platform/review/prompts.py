"""MRレビュー用のプロンプト(instructions)を組み立てる。

`docs/architecture.md` の Review の責務のうち、レビュープロンプトの設計(M1-8, #36)を担当する。
ここで返す文字列は、Claude Code Runner(`runner.SubprocessClaudeCodeRunner.run`)の
`instructions` 引数にそのまま渡す。Runner側の`_build_prompt`がこの文字列の直後に
MRタイトル・説明・コメント・diffを自動的に追記する(`docs/specs/claude-code-runner.md`)ため、
ここではMR固有のデータを一切含めず、「何を・どう見るか」という観点だけを書く。

指摘ごとの重要度/ファイル/行/根拠/提案をJSON/Markdownとして構造化する結果スキーマの定義は
M1-9(#37)の責務であり、ここでは扱わない。出力形式の指示は最小限に留めている。
"""

from __future__ import annotations

_FOCUS_POINTS = (
    "致命的なバグ(誤動作・クラッシュ・データ破損につながるもの)",
    "仕様や要件(MRのタイトル・説明、関連する docs/ の記述)との不整合",
    "既存コードの設計・命名・エラーハンドリング方針との不整合",
    "既存機能のデグレ(このMRによって、今まで動いていた挙動が壊れていないか)",
    "テスト不足(挙動を変えているのにテストが無い、既存テストが変更後の挙動と矛盾している)",
    "将来問題になりうる設計(拡張性を著しく損なう、技術的負債になりやすい実装)",
    "明らかな実装ミス(タイポ、ロジックの取り違え、境界値の考慮漏れ等)",
)

_SUPPRESS_POINTS = (
    "個人の好みレベルの指摘(フォーマットや命名の好みなど、レビュアーによって意見が割れるもの)",
    "大量の些末な指摘の羅列(ノイズになり、本当に重要な指摘が埋もれてしまうもの)",
)


def build_review_instructions() -> str:
    """MRレビュー用のinstructions文字列を返す。

    引数を取らない純粋関数。MRごとの情報(タイトル・説明・コメント・diff)は含めない。
    それらはRunner側が`instructions`の直後に自動で追記する。
    """
    focus = "\n".join(f"- {item}" for item in _FOCUS_POINTS)
    suppress = "\n".join(f"- {item}" for item in _SUPPRESS_POINTS)

    return f"""あなたは経験豊富なソフトウェアエンジニアです。これから提示するマージリクエスト(MR)をレビューしてください。

## 重視する観点
{focus}

## 抑制する観点(指摘しない)
{suppress}

## 進め方
このあとにMRのタイトル・説明・コメント・diffを提示しますが、diffの断片だけを見て判断しないでください。
必要に応じてこのリポジトリ自身を探索し、次のような情報を実際に確認したうえで判断してください。

- 変更されたファイルの、diffに現れていない周辺部分(変更箇所だけでなくファイル全体の文脈)
- 変更対象と関連する既存の実装(似た処理が他にどう書かれているか、命名やエラーハンドリングの慣習)
- 対応するテストコード(変更内容に対してテストが追加・更新されているか、既存テストが変更後の挙動と矛盾していないか)
- 関連するドキュメント(`docs/`配下の仕様・アーキテクチャ文書など)とMRの実装が整合しているか

想像や推測だけで指摘を作らず、実際にファイルを読んでから指摘してください。

## 出力
指摘ごとに、重要度・対象ファイル・行(わかる範囲で)・根拠・改善案を明記してください。
明確な根拠のある指摘のみを挙げ、確信が持てない点は指摘ではなく確認事項として分けて書いてください。
問題が見当たらない場合は、無理に指摘を作らず「特に指摘なし」と明記してください。
出力は日本語で書いてください。

(この指示の後に、レビュー対象のMRタイトル・説明・コメント・diffが続きます)"""


__all__ = ["build_review_instructions"]
